enum class ThemeType {
    // The names of the themes must not be changed, since they are used by Preferences for (de)serialization
    Light,
    Dark,
}

@Composable
@Suppress("UnusedReceiverParameter")
fun ThemeType?.prefersDarkTheme(): Boolean = true // R60i Control is always AMOLED dark

@Composable
fun OpenSCQ30Theme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    // Always use the AMOLED green scheme, regardless of system dark mode / dynamic colour.
    val colorScheme = darkColorScheme

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content,
    )
}

@Composable
fun OpenSCQ30GlanceTheme(dynamicColor: Boolean = true, content: @Composable () -> Unit) {
    GlanceTheme(
        colors = ColorProviders(light = darkColorScheme, dark = darkColorScheme),
    ) {
        content()
    }
}
